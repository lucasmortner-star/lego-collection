#!/usr/bin/env python3
"""
Price History Recorder
Appends dated price points to price-history.js, which powers the
per-set price charts on the site.

Each set has up to three series:
    value - the collection's current value (what data.js shows)
    new   - BrickLink New / Last 6 Months Sales avg (or MSRP while in production)
    used  - BrickLink Used / Last 6 Months Sales avg

A point is [date, price] or [date, price, source] when the price did not
come from BrickLink. Consecutive identical prices are not repeated.

Usage from the command line, with a JSON file of
{"<setNumber>": {"new": 352, "used": 241}, ...}:

    python scripts/record_prices.py prices.json [--source BrickEconomy] [--date 2026-11-09]
"""

import json
import os
import sys
from datetime import date

SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
PROJECT_DIR = os.path.dirname(SCRIPT_DIR)
HISTORY_FILE = os.path.join(PROJECT_DIR, "price-history.js")

PREFIX = "// Generated by scripts/record_prices.py - price points per set, oldest first.\nconst PRICE_HISTORY = "
SERIES = ("value", "new", "used")


def read_history(filepath=HISTORY_FILE):
    if not os.path.exists(filepath):
        return {}
    with open(filepath, "r", encoding="utf-8") as f:
        content = f.read()
    start = content.index("{")
    end = content.rindex("}") + 1
    return json.loads(content[start:end])


def write_history(history, filepath=HISTORY_FILE):
    # One set per line keeps git diffs readable
    lines = [f"  {json.dumps(k)}: {json.dumps(history[k], separators=(',', ':'), ensure_ascii=False)}"
             for k in sorted(history)]
    with open(filepath, "w", encoding="utf-8") as f:
        f.write(PREFIX + "{\n" + ",\n".join(lines) + "\n};\n")


def add_point(history, set_number, series, price, on_date, source=None):
    """Add one point. Returns True if the history changed."""
    if series not in SERIES or price is None or price <= 0:
        return False
    price = round(float(price), 2)
    if price == int(price):
        price = int(price)
    point = [on_date, price] + ([source] if source else [])
    points = history.setdefault(set_number, {}).setdefault(series, [])
    if points and points[-1][0] == on_date:
        if points[-1] == point:
            return False
        points[-1] = point
        return True
    if points and points[-1][1] == price:
        return False
    points.append(point)
    return True


def record(prices, source=None, on_date=None, filepath=HISTORY_FILE):
    """prices: {setNumber: {series: price}}. Returns number of points added."""
    on_date = on_date or date.today().isoformat()
    history = read_history(filepath)
    changed = 0
    for set_number, by_series in prices.items():
        for series, price in by_series.items():
            if add_point(history, str(set_number), series, price, on_date, source):
                changed += 1
    if changed:
        write_history(history, filepath)
    return changed


def main():
    args = sys.argv[1:]
    if not args:
        print(__doc__)
        sys.exit(1)
    source = None
    on_date = None
    if "--source" in args:
        i = args.index("--source")
        source = args[i + 1]
        del args[i:i + 2]
    if "--date" in args:
        i = args.index("--date")
        on_date = args[i + 1]
        del args[i:i + 2]
    with open(args[0], "r", encoding="utf-8") as f:
        prices = json.load(f)
    count = record(prices, source=source, on_date=on_date)
    print(f"Recorded {count} price points in price-history.js")


if __name__ == "__main__":
    main()
