#!/usr/bin/env python3
"""
Build set-minifigs-data.js: every minifigure that came in a set we own, with its
BrickLink used value, for the Minifigs page.

Input is a JSON file {"inv": {"<set>": [[figId, qty, name, category], ...]},
                      "pg":  {"<figId>": {"sNew", "sUsed", "cNew", "cUsed"}}}
scraped from BrickLink (set inventories and price guides, last 6 months).

Rules:
- A fig is counted once per copy of the set we own.
- Figs already in minifigs-data.js with fromSets (cabinet figs that came from that set)
  are not added again.
- A fig that is missing entirely is left out: mark its missing entries with
  missingFig: "<BrickLink id>". Figs only missing a part (entries with fig: "<id>") stay listed.
- Value: BrickLink 6-month used average, else current used asking average, else new.

    python3 scripts/build_set_minifigs.py bricklink_set_minifigs.json
"""
import json, os, re, subprocess, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FRANCHISE = {"STAR WARS": "Star Wars", "HARRY POTTER": "Harry Potter", "LORD OF THE RINGS / THE HOBBIT": "Lord of the Rings",
             "NINJAGO": "Ninjago", "MARVEL": "Marvel", "DC": "DC", "LEGO CITY": "City"}


def node_json(expr, files):
    js = "".join(f"eval(require('fs').readFileSync('{f}','utf8').replace(/^const (\\w+)/m,'global.$1'));" for f in files)
    return json.loads(subprocess.run(["node", "-e", js + f"console.log(JSON.stringify({expr}))"], cwd=ROOT,
                                     capture_output=True, text=True, check=True).stdout)


def main():
    src = json.load(open(sys.argv[1]))
    inv, pg = src["inv"], src["pg"]
    sets = node_json("LEGO_DATA.sets", ["data.js"])
    cabinet = node_json("MINIFIGS_DATA.minifigs", ["minifigs-data.js"])
    copies, info, missing_words = {}, {}, {}
    for s in sets:
        n = re.match(r"\d+", str(s["setNumber"])).group(0)
        copies[n] = copies.get(n, 0) + 1
        info.setdefault(n, s)
        for m in s.get("missing") or []:
            # Only a whole missing fig is left out; a fig missing a part stays listed
            if m.get("missingFig"):
                missing_words.setdefault(n, set()).add(m["missingFig"].lower())
    # cabinet figs that physically came from one of our sets
    taken = {}
    for c in cabinet:
        for n in c.get("fromSets") or []:
            taken[(c["id"], n)] = taken.get((c["id"], n), 0) + (c.get("qty") or 1)
    figs = {}
    for n, rows in inv.items():
        if n not in copies or not isinstance(rows, list):
            continue
        for fid, qty, name, cat in rows:
            if any(w in name.lower() or w == fid.lower() for w in missing_words.get(n, ())):
                continue
            q = qty * copies[n] - taken.get((fid, n), 0)
            if q <= 0:
                continue
            f = figs.setdefault(fid, {"id": fid, "name": name, "qty": 0, "fromSets": [],
                                      "franchise": FRANCHISE.get(info[n]["category"], "Castle & Other")})
            f["qty"] += q
            f["fromSets"].append(n)
    out = []
    for f in sorted(figs.values(), key=lambda f: (f["franchise"], f["name"])):
        p = pg.get(f["id"]) or {}
        val = next((p[k] for k in ("sUsed", "cUsed", "sNew", "cNew") if isinstance(p, dict) and p.get(k)), 0)
        out.append({"id": f["id"], "name": f["name"], "franchise": f["franchise"], "source": "Set",
                    "currentValue": round(val, 2), "owned": True, "qty": f["qty"], "fromSets": f["fromSets"], "inSet": True})
    lines = [json.dumps(o, ensure_ascii=False, separators=(", ", ": ")) for o in out]
    with open(os.path.join(ROOT, "set-minifigs-data.js"), "w", encoding="utf-8") as fh:
        fh.write("// Generated by scripts/build_set_minifigs.py: minifigures that came in sets we own.\n"
                 "// Values are BrickLink used averages (last 6 months); they are already part of each set's value.\n"
                 "const SET_MINIFIGS = [\n  " + ",\n  ".join(lines) + "\n];\n")
    print(f"{len(out)} figs, {sum(o['qty'] for o in out)} copies, ${sum(o['currentValue'] * o['qty'] for o in out):,.0f}")


if __name__ == "__main__":
    main()
